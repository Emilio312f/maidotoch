export const textos: Record<Idioma, Record<Clave, string>> = { es, en };

export function traducir(idioma: Idioma, clave: Clave, valores: Record<string, string | number> = {}): string {
  return Object.entries(valores).reduce((texto, [k, v]) => texto.replaceAll(`{${k}}`, String(v)), textos[idioma][clave]);
}

/** Texto para un código de error de la API; si no hay uno específico, el genérico. */
export function textoError(idioma: Idioma, codigo: string): string {
  const clave = `error.${codigo}` as Clave;
  return clave in textos[idioma] ? textos[idioma][clave] : textos[idioma]["error.generico"];
}
